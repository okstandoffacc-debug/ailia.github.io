-- Безопасное оформление заказа: блокирует товар от повторной покупки и создаёт заказ одной транзакцией.
create or replace function public.create_shop_order(
  p_product_ids bigint[], p_items jsonb, p_customer jsonb, p_address jsonb, p_delivery jsonb, p_total numeric
) returns bigint language plpgsql security definer set search_path = public as $$
declare new_order_id bigint; wanted_count integer; found_count integer;
begin
  if auth.uid() is null then raise exception 'Для оформления заказа войдите в аккаунт'; end if;
  wanted_count := coalesce(array_length(p_product_ids,1),0);
  if wanted_count = 0 then raise exception 'Корзина пуста'; end if;
  perform id from public.products where id = any(p_product_ids) and available = true for update;
  select count(*) into found_count from public.products where id = any(p_product_ids) and available = true;
  if found_count <> wanted_count then raise exception 'Один из товаров уже заказан. Обновите каталог'; end if;
  update public.products set available = false, sold_at = now(), updated_at = now() where id = any(p_product_ids) and available = true;
  if not found then raise exception 'Не удалось зарезервировать товар'; end if;
  insert into public.orders(user_id,items,customer,address,delivery,total,status)
  values(auth.uid(),coalesce(p_items,'[]'::jsonb),coalesce(p_customer,'{}'::jsonb),coalesce(p_address,'{}'::jsonb),coalesce(p_delivery,'{}'::jsonb),coalesce(p_total,0),'ordered')
  returning id into new_order_id;
  return new_order_id;
end; $$;
revoke all on function public.create_shop_order(bigint[],jsonb,jsonb,jsonb,jsonb,numeric) from public;
grant execute on function public.create_shop_order(bigint[],jsonb,jsonb,jsonb,jsonb,numeric) to authenticated;
