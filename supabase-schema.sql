-- Заказы покупателя и история доставки. Статусы меняет владелец вручную, пока не подключен API перевозчика.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb,
  customer jsonb not null default '{}'::jsonb,
  address jsonb not null default '{}'::jsonb,
  delivery jsonb not null default '{}'::jsonb,
  total numeric not null default 0,
  status text not null default 'ordered' check (status in ('ordered','sent','at_warehouse','ready_for_pickup','delivered','cancelled')),
  tracking_number text not null default '',
  status_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.orders enable row level security;
drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());
